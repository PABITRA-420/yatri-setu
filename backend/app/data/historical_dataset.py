def _clamp(value: float, min_val: float = 0.0, max_val: float = 100.0) -> float:
    return max(min_val, min(max_val, round(value, 1)))


def get_seasonal_factor(d: date) -> Dict[str, float]:
    """
    Computes seasonal modifiers for Himalayan tourism calendar:
    - Summer Peak: mid-April to mid-June (clear views, pleasant mountain weather)
    - Monsoon Trough: July to August (heavy rains, landslide hazards)
    - Autumn Peak: October to mid-November (Durga Puja, Diwali, clearest views)
    - Winter Peak/Chill: mid-December to early-January (Christmas/New Year surge)
    - Off-peak Winter: late January to February
    """
    month = d.month
    day = d.day

    if month in (4, 5, 6):
        # Summer peak
        tourism_mult = 1.35 if (month == 5 or (month == 4 and day >= 15) or (month == 6 and day <= 15)) else 1.20
        weather_score = 82.0
    elif month in (7, 8):
        # Monsoon trough
        tourism_mult = 0.55
        weather_score = 38.0
    elif month in (9,):
        # Shoulder recovery
        tourism_mult = 0.90
        weather_score = 68.0
    elif month in (10, 11):
        # Autumn peak
        tourism_mult = 1.45 if (month == 10 or (month == 11 and day <= 20)) else 1.15
        weather_score = 90.0
    elif month == 12:
        # Winter holidays
        tourism_mult = 1.35 if day >= 18 else 0.95
        weather_score = 65.0
    elif month == 1:
        # Early January holiday spillover, then cold trough
        tourism_mult = 1.15 if day <= 8 else 0.65
        weather_score = 52.0
    else:  # Feb, Mar
        tourism_mult = 0.80 if month == 2 else 1.05
        weather_score = 70.0

    return {"tourism_mult": tourism_mult, "weather_score": weather_score}


def generate_historical_dataset(
    start_date: date = date(2023, 1, 1),
    end_date: date = date(2023, 12, 31),
    seed: int = 42
) -> List[HistoricalObservation]:
    """
    Deterministically generates historical crowd observations across 6 destinations.
    Uses an isolated Random instance to ensure 100% reproducible results without
    interfering with application-level randomness.
    """
    rng = random.Random(seed)
    observations: List[HistoricalObservation] = []

    current_date = start_date
    delta_day = timedelta(days=1)

    while current_date <= end_date:
        d_str = current_date.isoformat()
        weekday = current_date.weekday() # 0 = Monday, 6 = Sunday
        is_weekend = weekday in (4, 5, 6) # Fri, Sat, Sun
        weekend_weight = 1.0 if weekday == 5 else (0.75 if weekday == 6 else (0.50 if weekday == 4 else 0.0))

        season_info = get_seasonal_factor(current_date)
        season_mult = season_info["tourism_mult"]
        base_weather = season_info["weather_score"]

        # Check for national or regional holiday
        holiday_info = KEY_HOLIDAYS_2023.get(d_str)
        event_info = REGIONAL_EVENTS_2023.get(d_str)

        for dest_id in DESTINATIONS:
            profile = DESTINATION_BASE_PROFILES[dest_id]
            base_p = profile["base_pressure"]

            # 1. Historical Footfall (0-100)
            footfall_raw = base_p * season_mult
            if is_weekend:
                footfall_raw += profile["weekend_boost"] * weekend_weight
            if holiday_info:
                footfall_raw *= profile["holiday_mult"]
            footfall_noise = rng.uniform(-3.5, 3.5)
            footfall = _clamp(footfall_raw + footfall_noise)

            # 2. Accommodation Occupancy (0-100) - highly correlated with footfall
            occ_noise = rng.uniform(-4.0, 4.0)
            accommodation = _clamp(footfall * 0.94 + occ_noise)

            # 3. Booking Demand (0-100) - forward booking intake
            book_noise = rng.uniform(-4.0, 4.0)
            booking = _clamp(footfall * 0.92 + (8.0 if is_weekend else 0.0) + book_noise)

            # 4. Search Demand (0-100) - leading indicator with slightly wider volatility
            search_noise = rng.uniform(-5.0, 5.0)
            search = _clamp(footfall * 0.88 + (12.0 if holiday_info else 0.0) + search_noise)

            # 5. Event Pressure (0-100)
            if event_info and (dest_id in ("darjeeling", "kalimpong") or rng.random() < 0.25):
                event_pressure = _clamp(event_info[1] + rng.uniform(-4.0, 4.0))
            else:
                # Ambient events
                event_pressure = _clamp(rng.uniform(5.0, 18.0) if is_weekend else rng.uniform(2.0, 10.0))

            # 6. Holiday Pressure (0-100)
            if holiday_info:
                holiday_pressure = _clamp(holiday_info[1] + rng.uniform(-2.5, 2.5))
            elif is_weekend:
                holiday_pressure = _clamp(rng.uniform(25.0, 40.0))
            else:
                holiday_pressure = _clamp(rng.uniform(5.0, 15.0))

            # 7. Weather Pressure (0-100, where 100 = optimal comfort, lower = severe weather)
            weather_noise = rng.uniform(-6.0, 6.0)
            weather = _clamp(base_weather + weather_noise)

            # 8. Traffic Pressure (0-100) - corridor telemetry (Hill Cart Road / NH10)
            traffic_base = (footfall * 0.70 + (20.0 if is_weekend else 5.0)) * profile["traffic_mult"]
            traffic_noise = rng.uniform(-4.0, 4.0)
            traffic = _clamp(traffic_base + traffic_noise)

            # Observed Ground Truth Pressure (0-100):
            # Formulated from standard signal blend + realistic physical ground-truth variance
            rule_blend = (
                0.15 * footfall +
                0.15 * accommodation +
                0.15 * booking +
                0.10 * search +
                0.10 * event_pressure +
                0.10 * holiday_pressure +
                0.10 * weather +
                0.15 * traffic
            )

            # Add authentic real-world telemetry noise (micro-shocks, localized gate surges)
            telemetry_variance = rng.gauss(0.0, 2.2)
            observed_pressure = _clamp(rule_blend + telemetry_variance)

            obs = HistoricalObservation(
                date=d_str,
                destination_id=dest_id,
                historical_footfall=footfall,
                accommodation_occupancy=accommodation,
                booking_demand=booking,
                search_demand=search,
                event_pressure=event_pressure,
                holiday_pressure=holiday_pressure,
                weather_pressure=weather,
                traffic_pressure=traffic,
                observed_pressure=observed_pressure,
                source="SYNTHETIC_GENERATOR",
                data_quality="HIGH",
                confidence=0.92
            )
            observations.append(obs)

        current_date += delta_day

    return observations


# Singleton cached dataset instance
_CACHED_DATASET: Optional[List[HistoricalObservation]] = None


def get_historical_dataset(force_regenerate: bool = False) -> List[HistoricalObservation]:
    """Provides access to the cached deterministic historical dataset."""
    global _CACHED_DATASET
    if _CACHED_DATASET is None or force_regenerate:
        _CACHED_DATASET = generate_historical_dataset()
    return _CACHED_DATASET


def export_dataset_to_csv(
    filepath: str = "data/historical/crowd_observations.csv",
    observations: Optional[List[HistoricalObservation]] = None
) -> str:
    """
    Exports the historical crowd observation dataset to standard CSV format
    suitable for offline analysis and ML training.
    """
    if observations is None:
        observations = get_historical_dataset()

    os.makedirs(os.path.dirname(filepath), exist_ok=True)

    fieldnames = [
        "date",
        "destination_id",
        "historical_footfall",
        "accommodation_occupancy",
        "booking_demand",
        "search_demand",
        "event_pressure",
        "holiday_pressure",
        "weather_pressure",
        "traffic_pressure",
        "observed_pressure",
        "source",
        "data_quality",
        "confidence"
    ]

    with open(filepath, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for obs in observations:
            writer.writerow(obs.model_dump())

    return os.path.abspath(filepath)
